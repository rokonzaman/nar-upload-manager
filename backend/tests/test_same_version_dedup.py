"""Same-version redeploy short-circuit tests.

Exercises deployment_service.run_deployment with a fake SSHClient that mimics
the surface the pipeline uses, proving:

  * a byte-identical remote file skips the backup download AND the upload,
    yet still records a Backup row and reaches SUCCESS;
  * a differing remote file still performs the transfer (backup download +
    upload), i.e. the fast path only short-circuits on an actual match.

The bundle's real sha256 is generated by the upload helper, so the fake
decides "identical" by comparing against the bundle's expected digest rather
than hashing real bytes.
"""

import hashlib
import pytest

from app.core.database import SessionLocal
from app.models.models import Deployment, DeploymentStatus
from app.services import deployment_service

from tests.conftest import upload_nar, create_server


class FakeSSHClient:
    """Fake for app.services.ssh_service.SSHClient.

    fs: dict remote_path -> bytes. fs_hashes: remote_path -> real sha256 hex.
    identical_sha: the digest the fake treats as "remote matches" — set it to
    the bundle's sha256 to simulate an identical redeploy, or to something
    else to simulate a real change.
    """

    fs = {}
    fs_hashes = {}
    identical_sha = ""

    def __init__(self, server, timeout=None):
        self.server = server
        self.bytes_moved = 0

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False

    def file_exists(self, remote_path):
        return remote_path in self.fs

    def remote_matches_sha256(self, remote_path, expected):
        return remote_path in self.fs and expected == self.identical_sha

    def download_file(self, remote_path, local_path):
        data = self.fs.get(remote_path)
        if data is None:
            raise RuntimeError(f"no such file: {remote_path}")
        with open(local_path, "wb") as fh:
            fh.write(data)
        self.bytes_moved += len(data)

    def upload_file(self, local_path, remote_path):
        with open(local_path, "rb") as fh:
            data = fh.read()
        self.fs[remote_path] = data
        self.fs_hashes[remote_path] = hashlib.sha256(data).hexdigest()
        self.bytes_moved += len(data)

    def remove_file(self, remote_path):
        self.fs.pop(remote_path, None)
        self.fs_hashes.pop(remote_path, None)

    def remote_sha256(self, remote_path):
        return self.fs_hashes.get(remote_path, "")

    def exec_command(self, command, timeout=None):
        return 0, "", ""


@pytest.fixture()
def fake_ssh(monkeypatch):
    FakeSSHClient.fs = {}
    FakeSSHClient.fs_hashes = {}
    FakeSSHClient.identical_sha = ""
    captured = []

    def make(server, timeout=None):
        client = FakeSSHClient(server, timeout=timeout)
        captured.append(client)
        return client

    monkeypatch.setattr(deployment_service, "SSHClient", make)
    return captured


def bundle_object(db, bundle_id):
    from app.models.models import NarBundle
    return db.query(NarBundle).filter(NarBundle.id == bundle_id).first()


def test_identical_redeploy_skips_transfer_but_records_backup(
    client, developer_headers, admin_headers, fake_ssh, monkeypatch
):
    resp = upload_nar(client, developer_headers, artifact="crgb-bulk-data", version="1.0.1")
    bundle = resp.json()[0]["bundle"]
    server = create_server(client, admin_headers, name="nifi-01", enabled=True)

    from app.models.models import NiFiServer

    db = SessionLocal()
    try:
        srv = db.query(NiFiServer).filter(NiFiServer.id == server["id"]).one()
        bnd = bundle_object(db, bundle["id"])

        # Simulate an identical file already on the target.
        remote_path = f"{srv.nar_directory}/{bnd.filename}"
        FakeSSHClient.fs[remote_path] = b"already-there"
        FakeSSHClient.identical_sha = bnd.sha256

        dep = deployment_service.create_deployment_records(
            db, bnd, [srv], deployed_by="developer"
        )[0]
        deployment_service.run_deployment(db, dep.id)
        db.refresh(dep)

        assert dep.status == DeploymentStatus.SUCCESS.value
        assert "byte-identical" in (dep.log or "")
        assert "Upload skipped" in (dep.log or "")
        # No backup-download and no upload happened.
        assert all(c.bytes_moved == 0 for c in fake_ssh)
        # ...but a Backup row was still written to the remote path we faked.
        from app.models.models import Backup
        rows = db.query(Backup).filter(Backup.deployment_id == dep.id).all()
        assert len(rows) == 1
        assert rows[0].original_path == remote_path
        assert rows[0].file_size == bnd.file_size
    finally:
        db.close()


def test_different_remote_file_still_transfers(
    client, developer_headers, admin_headers, fake_ssh, monkeypatch
):
    resp = upload_nar(client, developer_headers, artifact="crgb-bulk-data", version="1.0.1")
    bundle = resp.json()[0]["bundle"]
    server = create_server(client, admin_headers, name="nifi-01", enabled=True)

    from app.models.models import NiFiServer, Backup

    db = SessionLocal()
    try:
        srv = db.query(NiFiServer).filter(NiFiServer.id == server["id"]).one()
        bnd = bundle_object(db, bundle["id"])
        remote_path = f"{srv.nar_directory}/{bnd.filename}"

        # Existing file differs from the bundle -> identical_sha mismatch.
        FakeSSHClient.fs[remote_path] = b"old-different-content"
        FakeSSHClient.identical_sha = "deadbeef" * 8  # won't match

        dep = deployment_service.create_deployment_records(
            db, bnd, [srv], deployed_by="developer"
        )[0]
        deployment_service.run_deployment(db, dep.id)
        db.refresh(dep)

        # Different file: must backup-download the old bytes AND upload new ones.
        assert dep.status == DeploymentStatus.SUCCESS.value
        moved = sum(c.bytes_moved for c in fake_ssh)
        assert moved > 0
        assert FakeSSHClient.fs[remote_path] != b"old-different-content"
    finally:
        db.close()